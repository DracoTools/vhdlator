import vltest_bootstrap

test.scenarios('vlt')

# A design asking for more copies of its subprograms than the limit on copies
# of any one of them.  The limit is there to stop a recursion that folds to a
# new value at every call, which makes its copies of one subprogram; five
# subprograms called with nine hundred lengths each is a large design doing
# nothing wrong, and every call must still get its copy.  The formal is an
# array of unconstrained arrays, which nothing carries without a copy, so a
# call left without one is refused rather than quietly handled another way.
NFUNC = 5
NLEN = 900

test.top_filename = test.obj_dir + "/" + test.name + ".vhd"

lines = []
lines.append("-- Generated by " + test.name + ".py")
lines.append("package t_vhdl_speccap_pkg is")
lines.append("   type t_arr is array (natural range <>) of bit_vector;")
for f in range(NFUNC):
    lines.append("   function f%d (v : t_arr) return natural;" % f)
lines.append("end package;")
lines.append("")
lines.append("package body t_vhdl_speccap_pkg is")
for f in range(NFUNC):
    lines.append("   function f%d (v : t_arr) return natural is" % f)
    lines.append("   begin")
    lines.append("      return v(v'low)'length + %d;" % f)
    lines.append("   end function;")
lines.append("end package body;")
lines.append("")
lines.append("use work.t_vhdl_speccap_pkg.all;")
lines.append("")
lines.append("entity t_vhdl_speccap is")
lines.append("end entity;")
lines.append("")
lines.append("architecture a of t_vhdl_speccap is")
lines.append("begin")
lines.append("   p : process")
for n in range(1, NLEN + 1):
    lines.append("      constant c%d : t_arr(0 to 0)(1 to %d) := (0 => (others => '0'));" % (n, n))
lines.append("      variable s : natural := 0;")
lines.append("   begin")
for n in range(1, NLEN + 1):
    lines.append("      s := s + " + " + ".join("f%d(c%d)" % (f, n) for f in range(NFUNC)) + ";")
total = sum(n * NFUNC + NFUNC * (NFUNC - 1) // 2 for n in range(1, NLEN + 1))
lines.append("      assert s = %d report \"sum\" severity failure;" % total)
lines.append("      report \"*-* All Finished *-*\";")
lines.append("      wait;")
lines.append("   end process;")
lines.append("end architecture;")
test.write_wholefile(test.top_filename, "\n".join(lines) + "\n")

test.compile(verilator_flags=["-Mdir " + test.obj_dir, "--exe", "--build", "--main"],
             verilator_flags2=["--timing", "--top-module t_vhdl_speccap"],
             make_top_shell=False,
             make_main=False)

test.execute()

test.passes()
