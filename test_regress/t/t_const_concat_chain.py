import vltest_bootstrap

test.scenarios('simulator')

# A concatenation of many constants folds to one constant in one step. Folding
# it a pair at a time copied everything folded so far at every step, which is
# quadratic: a 16384-term ROM image took 53 s and 1.1 GB to fold.
test.top_filename = test.obj_dir + "/" + test.name + ".v"

WIDTHS = [1, 3, 8, 13, 32, 33, 64, 65]
NTERMS = 2000
terms = []
for i in range(NTERMS):
    w = WIDTHS[i % len(WIDTHS)]
    terms.append((w, (i * 2654435761 + 12345) & ((1 << w) - 1)))
total = sum(w for w, _ in terms)

lines = []
lines.append("// Generated by " + test.name + ".py")
lines.append("module t;")
lines.append("   logic [%d:0] big = {\n      %s};" %
             (total - 1, ",\n      ".join("%d'h%x" % (w, v) for w, v in terms)))
lines.append("   logic [23:0] trio = {8'h11, 8'h5a, 8'h22};")
lines.append("   logic [7:0] v;")
lines.append("   initial begin")
# The term that ends up at each end, and a spread of terms between
checks = sorted(set([0, 1, 2, NTERMS // 3, NTERMS // 2, NTERMS - 2, NTERMS - 1]))
for k in checks:
    after = sum(w for w, _ in terms[k + 1:])
    w, v = terms[k]
    lines.append("      if (big[%d -: %d] !== %d'h%x) begin" % (after + w - 1, w, w, v))
    lines.append("         $display(\"term %d: %%h\", big[%d -: %d]);" % (k, after + w - 1, w))
    lines.append("         $stop;")
    lines.append("      end")
lines.append("      if (trio !== 24'h115a22) $stop;")
# A value no pass can know, so the concatenation holding it is not one
# of constants and is left to the pairwise rules
lines.append("      v = 8'($urandom_range(32'h5a, 32'h5a));")
lines.append("      if ({8'h11, v, 8'h22} !== 24'h115a22) $stop;")
lines.append("      $write(\"*-* All Finished *-*\\n\");")
lines.append("      $finish;")
lines.append("   end")
lines.append("endmodule")
test.write_wholefile(test.top_filename, "\n".join(lines) + "\n")

test.compile(verilator_flags2=["--stats"])

if test.vlt_all:
    # "big" and "trio" fold whole; the third has a term that is not a constant
    test.file_grep(test.stats, r'Optimizations, Const concat chains\s+(\d+)', 2)

test.execute()

test.passes()
