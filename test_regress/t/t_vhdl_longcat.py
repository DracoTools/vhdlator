import vltest_bootstrap

test.scenarios('vlt')

# A VHDL constant written as a chain of thousands of "&": analysis asked each
# operand what types it could have again at every level it went down, which
# is quadratic in the length of the chain -- GHDL gna issue3002's 16384-term
# ROM image ran for more than five minutes. Each link is asked once now.
test.top_filename = test.obj_dir + "/" + test.name + ".vhd"

NTERMS = 4096
terms = [(i * 2654435761 + 12345) & 0xF for i in range(NTERMS)]
total = 4 * NTERMS

lines = []
lines.append("-- Generated by " + test.name + ".py")
lines.append("entity " + test.name + " is")
lines.append("end entity;")
lines.append("architecture test of " + test.name + " is")
lines.append("    constant init : bit_vector(%d downto 0) := (" % (total - 1))
lines.append(" &\n".join('        "%s"' % format(v, "04b") for v in terms) + ");")
lines.append("begin")
lines.append("    process is")
lines.append("    begin")
checks = sorted(set([0, 1, NTERMS // 3, NTERMS // 2, NTERMS - 2, NTERMS - 1]))
for k in checks:
    hi = total - 1 - 4 * k
    lines.append('        assert init(%d downto %d) = "%s" report "term %d" severity failure;' %
                 (hi, hi - 3, format(terms[k], "04b"), k))
lines.append('        report "*-* All Finished *-*";')
lines.append("        std.env.finish;")
lines.append("    end process;")
lines.append("end architecture;")
test.write_wholefile(test.top_filename, "\n".join(lines) + "\n")

test.compile(verilator_flags=["-Mdir " + test.obj_dir, "--exe", "--build", "--main"],
             verilator_flags2=["--timing", "--top-module " + test.name],
             make_top_shell=False,
             make_main=False)

test.execute()

test.passes()
